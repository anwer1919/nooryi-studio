export async function POST(req: Request) {
  try {
    // التحقق من المصادقة (اختياري — يمكن إزالته للسماح للزوار)
    const session = await auth()
    
    // قراءة الرسائل من الطلب
    const { messages } = await req.json()

    // التحقق من وجود الرسائل
    if (!messages || !Array.isArray(messages) || messages.length === 0) {
      return new Response(
        JSON.stringify({ error: "لم يتم استلام أي رسائل" }),
        { status: 400, headers: { "Content-Type": "application/json" } }
      )
    }

    // التحقق من متغير البيئة
    if (!process.env.GOOGLE_GENERATIVE_AI_API_KEY) {
      console.error("❌ [CHAT] GOOGLE_GENERATIVE_AI_API_KEY not configured")
      return new Response(
        JSON.stringify({ 
          error: "خدمة الذكاء الاصطناعي غير مهيأة — يرجى التواصل مع الدعم" 
        }),
        { status: 503, headers: { "Content-Type": "application/json" } }
      )
    }

    // استخدام Gemini 1.5 Flash (سريع ومجاني)
    const result = streamText({
      model: google("gemini-1.5-flash-latest"),
      system: SYSTEM_PROMPT,
      messages,
      temperature: 0.7,
      maxTokens: 1024,
      topP: 0.9,
    })

    // حفظ المحادثة في قاعدة البيانات (اختياري — للتحليلات)
    if (session?.user?.id) {
      try {
        const lastUserMessage = messages.filter(m => m.role === "user").pop()
        if (lastUserMessage) {
          await prisma.notification.create({
            data: {
              userId: session.user.id,
              title: "💬 محادثة مع المساعد الذكي",
              message: lastUserMessage.content.slice(0, 100),
              type: "chat_interaction",
            },
          }).catch(err => console.warn("⚠️ Failed to log chat:", err.message))
        }
      } catch (err) {
        // تجاهل أخطاء الحفظ — لا تؤثر على الرد
      }
    }

    return result.toDataStreamResponse()
  } catch (error: any) {
    console.error("❌ [CHAT API Error]:", error.message)
    return new Response(
      JSON.stringify({ 
        error: "عذراً، حدث خطأ في معالجة طلبك. يرجى المحاولة مرة أخرى.",
        details: process.env.NODE_ENV === "development" ? error.message : undefined
      }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    )
  }
}